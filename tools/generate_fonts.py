#!/usr/bin/env python3
"""Rebuild the checked-in font tables with fonttools4.68.0 and lv_font_conv1.5.3."""
import argparse
import hashlib
import json
from pathlib import Path
import re
import subprocess
from fontTools.ttLib import TTFont
from fontTools.varLib.instancer import instantiateVariableFont

ROOT = Path(__file__).resolve().parents[1]
FONTS = ROOT / 'firmware/ui/fonts'


def secret_table(source):
    text = source.read_text()
    bitmap_text = text.split('glyph_bitmap[] = {', 1)[1].split('};', 1)[0]
    bitmap_text = re.sub(r'/\*.*?\*/', '', bitmap_text, flags=re.S)
    bitmap = bytes(int(value, 16) for value in re.findall(r'0x([0-9a-f]+)', bitmap_text))
    descriptors = text.split('glyph_dsc[] = {', 1)[1].split('};', 1)[0]
    glyphs = [{key: int(value) for key, value in re.findall(r'\.(\w+) = (-?\d+)', item)}
              for item in re.findall(r'\{([^}]+)\}', descriptors)][1:]
    assert len(glyphs) == 95
    result = ['/* Generated by tools/generate_fonts.py; JetBrains Mono OFL-1.1. */',
              '#pragma once', '#include <stdint.h>',
              'static const uint8_t secret_glyph[95][24][8] = {']
    for glyph in glyphs:
        pixels = [[0] * 16 for _ in range(24)]
        for y in range(glyph['box_h']):
            for x in range(glyph['box_w']):
                index = y * glyph['box_w'] + x
                alpha = (bitmap[glyph['bitmap_index'] + index // 2] >> (0 if index % 2 else 4)) & 15
                px = 2 + glyph['ofs_x'] + x
                py = 18 - glyph['box_h'] - glyph['ofs_y'] + y
                assert 0 <= px < 16 and 0 <= py < 24
                pixels[py][px] = alpha
        result.append('  {' + ','.join('{' + ','.join(str(row[x] * 16 + row[x+1]) for x in range(0, 16, 2)) + '}' for row in pixels) + '},')
    result.append('};\n')
    (ROOT / 'firmware/p4/main/secret_glyphs.h').write_text('\n'.join(result))


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--converter', required=True, type=Path)
    args = parser.parse_args()
    work = ROOT / '.cache/fonts'
    work.mkdir(parents=True, exist_ok=True)
    for name in ('Inter', 'JetBrainsMono'):
        font = TTFont(FONTS / 'source' / f'{name}.woff2')
        font.flavor = None
        if 'fvar' in font:
            font = instantiateVariableFont(font, {'wght': 500}, inplace=True)
        font.save(work / f'{name}.ttf')
    for name, family, size in [('font_body16', 'Inter', 16), ('font_body18', 'Inter', 18),
                               ('font_title22', 'JetBrainsMono', 22), ('font_title26', 'JetBrainsMono', 26),
                               ('secret_font', 'JetBrainsMono', 18)]:
        output = work / 'secret_font.c' if name == 'secret_font' else FONTS / f'{name}.c'
        subprocess.run([str(args.converter), '--font', str(work / f'{family}.ttf'), '--size', str(size),
                        '--bpp', '4', '--format', 'lvgl', '--range', '0x20-0x7e' if name == 'secret_font' else '0x20-0x7e,0xa0-0xff',
                        '--no-compress', '--no-prefilter', '--lv-font-name', name, '-o', str(output)], check=True)
        generated = output.read_text()
        generated = re.sub(r' \* Opts:.*', ' * Generated by tools/generate_fonts.py from the checked-in OFL font source.', generated)
        output.write_text(generated.rstrip()+"\n")
    secret_table(work / 'secret_font.c')
    provenance = {'family': 'JetBrains Mono', 'license': 'OFL-1.1', 'size_px': 18,
                  'bpp': 4, 'cell': [16, 24], 'range': [32, 126],
                  'conversion': 'Uncompressed row-major LVGL glyph alpha, centered in bounded cells. Every pixel bounds checked.',
                  'source_sha256': hashlib.sha256((FONTS / 'source/JetBrainsMono.woff2').read_bytes()).hexdigest()}
    (ROOT / 'firmware/p4/main/secret-glyph-provenance.json').write_text(json.dumps(provenance, indent=2) + '\n')

if __name__ == '__main__':
    main()
