//! Bounded, allocation-free NIP44 version 2 payload encryption.
//!
//! These are cryptographic primitives, not device authorization. A caller must
//! obtain local consent, supply a fresh CSPRNG nonce for each encryption, and
//! verify the enclosing event before decrypting an authenticated message. A MAC
//! alone does not establish a sender: either conversation participant can make it.
//! Conversation keys are not cached or exported. Callers own the lifetime of
//! input plaintext and successful output; all output bytes are cleared on error.

use crate::nip19::SecretKey;
use base64ct::{Base64, Encoding};
use chacha20::ChaCha20;
use cipher::{KeyIvInit, StreamCipher};
use hkdf::Hkdf;
use hmac::{Hmac, KeyInit, Mac};
use k256::{ecdh::diffie_hellman, PublicKey};
use sha2::Sha256;
use zeroize::{Zeroize, Zeroizing};

/// Maximum primitive plaintext size in UTF-8 bytes, not characters.
/// Enclosing seals need more space than their user-visible message content;
/// callers must apply their own complete-flow and transport bounds too.
pub const MAX_PLAINTEXT_BYTES: usize = 4096;
const MAX_BINARY_BYTES: usize = 1 + 32 + 2 + MAX_PLAINTEXT_BYTES + 32;
/// Maximum standard padded Base64 payload size for this fixed power-of-two bound.
pub const MAX_PAYLOAD_BYTES: usize = MAX_BINARY_BYTES.div_ceil(3) * 4;
const VERSION: u8 = 2;

/// Bounded NIP44 failures. Errors never include secret or plaintext data.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum Error {
    /// Empty, malformed or unsupported-size plaintext/payload.
    InvalidInput,
    /// A scalar or x-only public key is invalid.
    InvalidKey,
    /// The payload uses an unsupported encryption version.
    UnsupportedVersion,
    /// The message authentication code does not match.
    Authentication,
    /// The caller's output cannot hold the complete result.
    OutputTooSmall,
}

fn padded_len(length: usize) -> Result<usize, Error> {
    if !(1..=MAX_PLAINTEXT_BYTES).contains(&length) {
        return Err(Error::InvalidInput);
    }
    if length <= 32 {
        return Ok(32);
    }
    let next = length.next_power_of_two();
    let chunk = if next <= 256 { 32 } else { next / 8 };
    Ok(length.div_ceil(chunk) * chunk)
}

fn conversation_key(secret: &SecretKey, peer: &[u8; 32]) -> Result<Zeroizing<[u8; 32]>, Error> {
    // Nostr public keys are x-only. Either lift has the same shared x coordinate.
    let mut encoded = [0u8; 33];
    encoded[0] = 2;
    encoded[1..].copy_from_slice(peer);
    let public = PublicKey::from_sec1_bytes(&encoded).map_err(|_| Error::InvalidKey)?;
    let secret = k256::SecretKey::from_slice(secret.as_bytes()).map_err(|_| Error::InvalidKey)?;
    let scalar = Zeroizing::new(secret.to_nonzero_scalar());
    let shared = diffie_hellman(&*scalar, public.as_affine());
    let (prk, _expand) = Hkdf::<Sha256>::extract(Some(b"nip44-v2"), shared.raw_secret_bytes());
    let prk = Zeroizing::new(prk);
    let mut key = Zeroizing::new([0; 32]);
    key.copy_from_slice(&prk);
    Ok(key)
}

fn message_keys(key: &[u8; 32], nonce: &[u8; 32]) -> Zeroizing<[u8; 76]> {
    let mut output = Zeroizing::new([0; 76]);
    // Fixed SHA256 PRK and output lengths satisfy RFC5869's size constraints.
    Hkdf::<Sha256>::from_prk(key)
        .expect("32-byte PRK")
        .expand(nonce, &mut *output)
        .expect("76-byte HKDF output");
    output
}

fn mac(key: &[u8], nonce: &[u8; 32], ciphertext: &[u8]) -> Hmac<Sha256> {
    let mut mac = Hmac::<Sha256>::new_from_slice(key).expect("HMAC accepts a 32-byte key");
    mac.update(nonce);
    mac.update(ciphertext);
    mac
}

/// Encrypt UTF-8 plaintext into standard padded Base64 NIP44 v2.
///
/// `nonce` must be freshly generated by a trusted CSPRNG for every message.
/// This function does not grant consent or sign the required enclosing event.
/// Returns the complete output length; the unused suffix is zero.
pub fn encrypt(
    secret: &SecretKey,
    peer: &[u8; 32],
    plaintext: &str,
    nonce: &[u8; 32],
    output: &mut [u8],
) -> Result<usize, Error> {
    output.zeroize();
    let result = encrypt_inner(secret, peer, plaintext, nonce, output);
    if result.is_err() {
        output.zeroize();
    }
    result
}

fn encrypt_inner(
    secret: &SecretKey,
    peer: &[u8; 32],
    plaintext: &str,
    nonce: &[u8; 32],
    output: &mut [u8],
) -> Result<usize, Error> {
    let padded = padded_len(plaintext.len())?;
    let binary_len = 1 + 32 + 2 + padded + 32;
    if output.len() < binary_len.div_ceil(3) * 4 {
        return Err(Error::OutputTooSmall);
    }
    let key = conversation_key(secret, peer)?;
    let keys = message_keys(&key, nonce);
    let mut binary = Zeroizing::new([0u8; MAX_BINARY_BYTES]);
    binary[0] = VERSION;
    binary[1..33].copy_from_slice(nonce);
    let end = 33 + 2 + padded;
    let ciphertext = &mut binary[33..end];
    ciphertext[..2].copy_from_slice(&(plaintext.len() as u16).to_be_bytes());
    ciphertext[2..2 + plaintext.len()].copy_from_slice(plaintext.as_bytes());
    ChaCha20::new_from_slices(&keys[..32], &keys[32..44])
        .map_err(|_| Error::InvalidInput)?
        .try_apply_keystream(ciphertext)
        .map_err(|_| Error::InvalidInput)?;
    let tag = mac(&keys[44..], nonce, ciphertext).finalize().into_bytes();
    binary[end..binary_len].copy_from_slice(&tag);
    Base64::encode(&binary[..binary_len], output)
        .map(str::len)
        .map_err(|_| Error::OutputTooSmall)
}

/// Authenticate and decrypt a bounded NIP44 v2 payload into caller-owned UTF-8.
///
/// Verify the enclosing event first when authenticating a message sender.
/// `peer` is the ECDH peer, which may be an ephemeral wrapping key. The MAC is
/// checked before any plaintext is exposed. Every failure clears all of `output`.
/// On success only the returned prefix holds plaintext; the suffix is zero.
pub fn decrypt(
    secret: &SecretKey,
    peer: &[u8; 32],
    payload: &str,
    output: &mut [u8],
) -> Result<usize, Error> {
    output.zeroize();
    let result = decrypt_inner(|| conversation_key(secret, peer), payload, output);
    if result.is_err() {
        output.zeroize();
    }
    result
}

fn decrypt_inner(
    derive_key: impl FnOnce() -> Result<Zeroizing<[u8; 32]>, Error>,
    payload: &str,
    output: &mut [u8],
) -> Result<usize, Error> {
    if payload.starts_with('#') {
        return Err(Error::UnsupportedVersion);
    }
    if !(132..=MAX_PAYLOAD_BYTES).contains(&payload.len()) {
        return Err(Error::InvalidInput);
    }
    let mut binary = Zeroizing::new([0u8; MAX_BINARY_BYTES]);
    let length = Base64::decode(payload, &mut *binary)
        .map_err(|_| Error::InvalidInput)?
        .len();
    if length < 99 {
        return Err(Error::InvalidInput);
    }
    if binary[0] != VERSION {
        return Err(Error::UnsupportedVersion);
    }
    let nonce: &[u8; 32] = binary[1..33].try_into().map_err(|_| Error::InvalidInput)?;
    // Bound and decode unauthenticated input before the expensive curve operation.
    let key = derive_key()?;
    let keys = message_keys(&key, nonce);
    let end = length - 32;
    mac(&keys[44..], nonce, &binary[33..end])
        .verify_slice(&binary[end..length])
        .map_err(|_| Error::Authentication)?;
    let padded = &mut binary[33..end];
    ChaCha20::new_from_slices(&keys[..32], &keys[32..44])
        .map_err(|_| Error::InvalidInput)?
        .try_apply_keystream(padded)
        .map_err(|_| Error::InvalidInput)?;
    let plain_len = u16::from_be_bytes([padded[0], padded[1]]) as usize;
    // Extended prefixes start with zero and cannot fit this device's bound.
    if 2 + padded_len(plain_len)? != padded.len() {
        return Err(Error::InvalidInput);
    }
    let plaintext = &padded[2..2 + plain_len];
    core::str::from_utf8(plaintext).map_err(|_| Error::InvalidInput)?;
    let target = output.get_mut(..plain_len).ok_or(Error::OutputTooSmall)?;
    target.copy_from_slice(plaintext);
    Ok(plain_len)
}

